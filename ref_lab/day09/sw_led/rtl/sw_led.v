// =============================================================================
// Day 09 — sw_led.v
// 조합논리 첫걸음: assign 한 줄의 설계.
//   led   = sw   : 통과(pass-through) — 배선만
//   led_n = ~sw  : 연산(compute)      — 비트 반전
// 클럭·레지스터 없음 — 입력이 바뀌면 출력이 즉시 따라간다.
// =============================================================================
//   sw[3:0]   → 슬라이드 스위치 SW0~SW3
//   led[3:0]  → 단색 User LED LD4~LD7 (통과)
//   led_n[3:0]→ 반전 출력 — RGB LED 파란 채널에 연결(단색 녹색과 색 구분)
// =============================================================================
module sw_led (
  input  wire [3:0] sw,    // 슬라이드 스위치 SW0~SW3
  output wire [3:0] led,   // User LED LD4~LD7 — 통과
  output wire [3:0] led_n  // 반전 출력 (RGB 파랑) — 연산
);

  assign led   = sw;       // 통과(pass-through): 배선만
  assign led_n = ~sw;      // 연산(compute): 비트 반전

endmodule
