// Day 09 ― mux4.v
// case 문 기반 4:1 컬러 MUX.
// 슬라이드 스위치 2개(sel)로 미리 정의한 4색 중 하나를 골라 RGB LED 로 출력.
// 클럭·레지스터 없는 순수 조합논리 ― 입력이 바뀌면 출력이 즉시 따라간다.
// =============================================================================
//   sel = sw[1:0] →
//     00 : R 빨강 (3'b100)   01 : G 초록 (3'b010)
//     10 : B 파랑 (3'b001)   11 : W 흰색 (3'b111)
//
//   채널 규약 : rgb[2:0] = {R, G, B}  (rgb[2]=R, rgb[1]=G, rgb[0]=B)
//
//   full-case 와 latch : 조합 always 는 *모든* 입력 조합에 출력을 대입해야 한다.
//     sel 2비트의 4 조합(00·01·10·11)을 다 기술하면 그 자체로 full-case →
//     default 가 없어도 latch 는 추론되지 않는다. latch 는 case 가 *불완전* 하고
//     default 도 없을 때 생긴다(미기술 값에서 직전 값 유지, Day 06).
//     아래 default 는 향후 case 누락 방지 + sel 의 X/Z 시뮬 방어용 안전망.
// =============================================================================
module mux4 (
  input  wire [1:0] sw,    // sw[1:0] = sel ― 색 선택
  output reg  [2:0] rgb    // 선택된 색 → RGB LED  ({R,G,B})
);

  always @* begin            // 조합논리 (클럭 없음)
    case (sw)                // 2비트로 4색 중 하나 선택
      2'd0: rgb = 3'b100;    // R 빨강
      2'd1: rgb = 3'b010;    // G 초록
      2'd2: rgb = 3'b001;    // B 파랑
      2'd3: rgb = 3'b111;    // W 흰색
      default: rgb = 3'b000; // 4조합이라 이미 full-case · default는 X/Z 안전망
    endcase
  end

endmodule
